    for i,ch in enumerate(COURSE):
        target=OUT/ch['group']/(ch['slug']+'.md')
        target.parent.mkdir(parents=True,exist_ok=True)
        content,records=render(ch,i)
        target.write_text(content,encoding='utf-8',newline='\n')
        evidence.extend(records)
        stats.append({'path':target.relative_to(OUT).as_posix(),'lines':len(content.splitlines()),'characters':len(content)})
    (OUT/'_evidence/source-excerpts.json').write_text(json.dumps({'revision':REV,'excerpts':evidence},ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
