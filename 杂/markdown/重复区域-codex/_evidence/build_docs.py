def paragraphs(text):
    return '\n\n'.join(s+'。' for s in text.split('。') if s.strip())

def excerpt(key,start,end):
    path=P[key]
    raw=(ROOT/path).read_bytes()
    lines=raw.decode('utf-8').splitlines()
    end=len(lines) if end is None else end
    if not (1 <= start <= end <= len(lines)):
        raise ValueError((path,start,end,len(lines)))
    return path,start,end,'\n'.join(lines[start-1:end]),hashlib.sha256(raw).hexdigest()

